from __future__ import annotations

import os
import re
from typing import Dict


def build_prompt(question: str, ctx: str, cites: Dict[int, str], intent: str = 'course_info') -> str:
    require_citations = (os.getenv('RAG_REQUIRE_CITATIONS', '0') or '0').strip().lower() in (
        '1', 'true', 'yes', 'on'
    )

    allowed_cites: list[str] = []
    seen: set[str] = set()
    for c in (cites or {}).values():
        s = (c or '').strip()
        if not s or s in seen:
            continue
        seen.add(s)
        allowed_cites.append(s)

    allowed_block = "\n".join([f"- [{c}]" for c in allowed_cites])

    multi_doc_hint = (os.getenv('RAG_MULTI_DOC_HINTS', '1') or '1').strip().lower() in (
        '1', 'true', 'yes', 'on'
    )

    multi_doc_guidance = ""
    if multi_doc_hint and any(line.startswith('[Source:') for line in (ctx or '').splitlines()):
        multi_doc_guidance = (
            "8) หากคำตอบต้องอาศัยหลายเอกสาร ให้แยกเป็นประเด็น ๆ และระบุว่าแต่ละประเด็นอ้างอิงจากเอกสารใด.\n"
            "9) หากมีข้อมูลขัดแย้งกัน ให้ชี้ให้เห็นความขัดแย้งและอ้างอิงแยกตามเอกสาร.\n"
            "10) หากหลักฐานไม่ครบทุกเงื่อนไข ให้ระบุชัดเจนว่ายังขาดข้อมูลส่วนใด.\n"
        )

    intent_guidance = ""
    if intent in ('course_info', 'curriculum_course_info'):
        intent_guidance = "คำถามนี้เกี่ยวกับเนื้อหารายวิชา กรุณาระบุชื่อวิชา (ไทยและอังกฤษถ้ามี) และจำนวนหน่วยกิตให้ครบถ้วนเสมอ\n"
    elif intent in ('prerequisite', 'prerequisite_lookup'):
        intent_guidance = "คำถามนี้เกี่ยวกับวิชาบังคับก่อน ให้โฟกัสแค่รหัสวิชาที่บังคับก่อนและเงื่อนไขที่เกี่ยวข้อง โดยไม่ต้องอธิบายเนื้อหารายวิชานั้น\n"
    elif intent in ('regulation', 'exam_policy', 'academic_status_policy', 'registration_policy'):
        intent_guidance = "คำถามนี้เกี่ยวกับกฎระเบียบ ให้ตอบอ้างอิงระเบียบหรือมาตราอย่างชัดเจน หากมีข้อยกเว้นหรือบทลงโทษ ให้ระบุด้วย\n"
    elif intent == 'multi_intent':
        intent_guidance = "คำถามนี้มีหลายประเด็นย่อย ให้ตอบแยกเป็นส่วนๆ ให้ครบทุกประเด็นอย่างชัดเจน\n"
    elif intent == 'claim_verification':
        intent_guidance = (
            "คำถามนี้เป็นการตรวจสอบ claim แบบ ใช่/ไม่ใช่\n"
            "- ต้องตอบบรรทัดแรกเป็น 'ใช่' หรือ 'ไม่ใช่' เท่านั้น\n"
            "- หากข้อความในคำถามขัดกับหลักฐาน ให้ตอบ 'ไม่ใช่'\n"
            "- หากหลักฐานที่ให้ไม่พอสำหรับตัดสิน ให้ตอบว่า 'ไม่พบข้อมูลที่ยืนยันได้จากเอกสารสำหรับคำถามแบบใช่หรือไม่'\n"
            "- บรรทัดถัดไปให้เหตุผลสั้นๆ จากหลักฐาน ห้ามเปลี่ยนเป็นการ์ดข้อมูลวิชาทั่วไป\n"
        )
    elif intent in ('credit_lookup', 'instructor_lookup', 'general_info'):
        intent_guidance = "คำถามนี้ต้องการ fact เดียว ให้ตอบสั้น กระชับ และตรงรูปแบบคำถามโดยไม่แตกประเด็นเกินจำเป็น\n"

    clause_guard = ""
    m_clause = re.search(r"ข้อ\s*([๐-๙0-9]+(?:\.[๐-๙0-9]+)?)", question or "")
    if m_clause:
        clause = (m_clause.group(1) or '').translate(str.maketrans("๐๑๒๓๔๕๖๗๘๙", "0123456789"))
        clause_guard = (
            f"11) ต้องตอบจาก 'ข้อ {clause}' ที่ถูกถามเท่านั้น ห้ามอ้างข้ออื่นแทน.\n"
            f"12) ถ้าในบริบทไม่มีข้อ {clause} ให้ตอบว่าไม่พบข้อความยืนยันของข้อที่ถามโดยตรง.\n"
        )

    exact_schema_intents = {
        'prerequisite',
        'prerequisite_lookup',
        'claim_verification',
        'exam_policy',
        'academic_status_policy',
        'registration_policy',
    }
    use_exact_schema = intent in exact_schema_intents

    schema_block_with_cites = (
        "9) จัดรูปแบบคำตอบตาม schema นี้เสมอ (เป็น bullet):\n"
        "   - สรุปคำตอบ: ...\n"
        "   - หลักฐาน: ... [source/page]\n"
        "   - เงื่อนไข/ข้อยกเว้น: ...\n"
        "   - สถานะความครบถ้วนของหลักฐาน: ครบ/ยังขาดข้อมูล ...\n"
        "10) ถ้าหลักฐานไม่พอสำหรับยืนยันคำตอบ ให้ตอบว่า 'ไม่พบข้อความยืนยันโดยตรงในเอกสารที่ค้นได้' และระบุว่าขาดข้อมูลส่วนใด.\n"
    )
    schema_block_plain = (
        "9) จัดรูปแบบคำตอบตาม schema นี้เสมอ (เป็น bullet):\n"
        "   - สรุปคำตอบ: ...\n"
        "   - หลักฐาน: ...\n"
        "   - เงื่อนไข/ข้อยกเว้น: ...\n"
        "   - สถานะความครบถ้วนของหลักฐาน: ครบ/ยังขาดข้อมูล ...\n"
        "10) ถ้าหลักฐานไม่พอสำหรับยืนยันคำตอบ ให้ตอบว่า 'ไม่พบข้อความยืนยันโดยตรงในเอกสารที่ค้นได้' และระบุว่าขาดข้อมูลส่วนใด.\n"
    )
    natural_style_with_cites = (
        "9) สำหรับคำถาม fact/general ให้ตอบแบบธรรมชาติได้เป็น 1-3 bullet หรือ 1 ย่อหน้าสั้น ๆ โดยไม่ต้องยัด schema เดิมถ้าไม่จำเป็น.\n"
        "10) ถ้าตอบได้ ให้ขึ้นคำตอบหลักก่อน แล้วค่อยเสริมรายละเอียดหรือข้อควรรู้ที่เกี่ยวข้อง.\n"
        "11) ถ้าหลักฐานไม่พอ ห้ามตอบซ้ำแนว 'ไม่พบเอกสาร' อย่างเดียว ให้ระบุด้วยว่าระบบยังขาดอะไร และควรถาม/ค้นต่อแบบไหน.\n"
    )
    natural_style_plain = (
        "9) สำหรับคำถาม fact/general ให้ตอบแบบธรรมชาติได้เป็น 1-3 bullet หรือ 1 ย่อหน้าสั้น ๆ โดยไม่ต้องยัด schema เดิมถ้าไม่จำเป็น.\n"
        "10) ถ้าตอบได้ ให้ขึ้นคำตอบหลักก่อน แล้วค่อยเสริมรายละเอียดหรือข้อควรรู้ที่เกี่ยวข้อง.\n"
        "11) ถ้าหลักฐานไม่พอ ห้ามตอบซ้ำแนว 'ไม่พบเอกสาร' อย่างเดียว ให้ระบุด้วยว่าระบบยังขาดอะไร และควรถาม/ค้นต่อแบบไหน.\n"
    )

    if require_citations:
        instruction = (
            "คุณคือผู้ช่วยของภาควิชาวิศวกรรมคอมพิวเตอร์ ณ มหาวิทยาลัยเทคโนโลยีพระจอมเกล้าธนบุรี ตอบเป็นภาษาไทย.\n"
            "หลักการตอบ:\n"
            "1) ใช้เฉพาะข้อมูลในบริบทที่ให้ หากคำตอบหลักมีหลักฐานครบ ให้ตอบตรง ๆ โดยไม่ต้องเติมข้อความปฏิเสธท้ายคำตอบ.\n"
            "2) ให้ตอบเป็น bullet เป็นหลัก (ขึ้นต้นด้วย '- ') และแต่ละ bullet ต้องลงท้ายด้วยการอ้างอิงอย่างน้อย 1 รายการต่อบรรทัด โดยใส่ท้ายบรรทัดในรูปแบบ [source/page].\n"
            "3) หากคำถามมีหลายประเด็น/หลายคำถามย่อย ให้ตอบให้ครบทุกประเด็น โดยแยก 1 bullet ต่อ 1 ประเด็น.\n"
            "4) ห้ามเดาข้อมูลนอกรายการที่มี ใช้เฉพาะข้อมูลที่มีในบริบทเท่านั้น.\n"
            "5) หากคำถามขอ 'สรุป' หรือ 'โครงสร้าง' ให้จัดลำดับหัวข้อก่อนรายละเอียด.\n"
            "6) หากคำถามกำกวม/สั้นมาก (เช่น พิมพ์แค่ชื่อภาษา หรือ xxx) ให้ถามกลับ 1 คำถามสั้น ๆ เพื่อขอรายละเอียดที่จำเป็นก่อน.\n"
            "   เมื่อถามกลับ ให้ตอบเพียงคำถามเดียวสั้น ๆ เท่านั้น และห้ามใส่สรุปคำตอบ หลักฐาน เงื่อนไข หรือสถานะความครบถ้วนเพิ่มเติม.\n"
            "7) ห้ามให้ URL/ลิงก์ภายนอก เว้นแต่ URL นั้นปรากฏอยู่ในบริบท.\n"
            "8) เรื่องวัน/วันที่/เดดไลน์: ให้ระบุเฉพาะวันที่ที่มีข้อความยืนยันตรง ๆ ในบริบทเท่านั้น ห้ามอนุมานเดดไลน์จากคำว่า 'ประกาศ ณ วันที่ ...' หรือวันที่ที่ไม่ได้ระบุว่าเป็นกำหนดการ/เส้นตาย.\n"
            f"{schema_block_with_cites if use_exact_schema else natural_style_with_cites}"
            f"{multi_doc_guidance}"
            f"{clause_guard}"
            f"คำแนะนำพิเศษ: {intent_guidance}"
        )
    else:
        instruction = (
            "คุณคือผู้ช่วยของภาควิชาวิศวกรรมคอมพิวเตอร์ ณ มหาวิทยาลัยเทคโนโลยีพระจอมเกล้าธนบุรี ตอบเป็นภาษาไทย.\n"
            "หลักการตอบ:\n"
            "1) ใช้เฉพาะข้อมูลในบริบทที่ให้ หากคำตอบหลักมีหลักฐานครบ ให้ตอบตรง ๆ โดยไม่ต้องเติมข้อความปฏิเสธท้ายคำตอบ.\n"
            "2) ให้ตอบเป็น bullet เป็นหลัก (ขึ้นต้นด้วย '- ') และตอบให้ตรงคำถาม กระชับ ชัดเจน.\n"
            "3) หากคำถามมีหลายประเด็น/หลายคำถามย่อย ให้ตอบให้ครบทุกประเด็น โดยแยก 1 bullet ต่อ 1 ประเด็น.\n"
            "4) ห้ามเดาข้อมูลนอกรายการที่มี ใช้เฉพาะข้อมูลที่มีในบริบทเท่านั้น.\n"
            "5) หากคำถามขอ 'สรุป' หรือ 'โครงสร้าง' ให้จัดลำดับหัวข้อก่อนรายละเอียด.\n"
            "6) หากคำถามกำกวม/สั้นมาก (เช่น พิมพ์แค่ชื่อภาษา หรือ xxx) ให้ถามกลับ 1 คำถามสั้น ๆ เพื่อขอรายละเอียดที่จำเป็นก่อน.\n"
            "   เมื่อถามกลับ ให้ตอบเพียงคำถามเดียวสั้น ๆ เท่านั้น และห้ามใส่สรุปคำตอบ หลักฐาน เงื่อนไข หรือสถานะความครบถ้วนเพิ่มเติม.\n"
            "7) ห้ามให้ URL/ลิงก์ภายนอก เว้นแต่ URL นั้นปรากฏอยู่ในบริบท.\n"
            "8) เรื่องวัน/วันที่/เดดไลน์: ให้ระบุเฉพาะวันที่ที่มีข้อความยืนยันตรง ๆ ในบริบทเท่านั้น ห้ามอนุมานเดดไลน์จากคำว่า 'ประกาศ ณ วันที่ ...' หรือวันที่ที่ไม่ได้ระบุว่าเป็นกำหนดการ/เส้นตาย.\n"
            f"{schema_block_plain if use_exact_schema else natural_style_plain}"
            f"{multi_doc_guidance}"
            f"{clause_guard}"
            f"คำแนะนำพิเศษ: {intent_guidance}"
        )

    if require_citations:
        return (
            f"{instruction}\n"
            f"คำถาม:\n{question}\n\n"
            f"บริบท:\n{ctx}\n\n"
            f"รายชื่ออ้างอิงที่อนุญาต (ใช้ได้เฉพาะรายการนี้เท่านั้น):\n{allowed_block}\n\n"
            f"คำตอบ:\n"
        )
    return (
        f"{instruction}\n"
        f"คำถาม:\n{question}\n\n"
        f"บริบท:\n{ctx}\n\n"
        f"คำตอบ:\n"
    )
